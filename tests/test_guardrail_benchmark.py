"""A regression gate on the number-and-link guardrail, using eval/guardrail_benchmark.py (deterministic, no model).

The floors are the measured results with a little room: every fabricated amount and link caught (417 of 417 when written), no
grounded one blocked (0 of 258). A change to the extraction patterns that starts missing a format, or starts blocking figures the
conversation established, fails here before it reaches a borrower. The cases are template-generated by the engineer who wrote the
check, so a pass means "no regression on the formats it was built for", not "no hallucination can get through".
"""

import pytest

from eval import guardrail_benchmark as gb


@pytest.fixture(scope="module")
def summary():
    return gb.run()


def test_fabricated_amounts_and_links_are_caught(summary):
    caught = summary["fabricated_caught"]
    assert caught["k"] / caught["n"] >= 0.98, summary["missed_examples"]


def test_figures_the_conversation_established_are_not_blocked(summary):
    assert summary["grounded_wrongly_blocked"]["k"] <= 1, summary["wrongly_blocked_examples"]


def test_the_cases_cover_every_format_the_model_writes(summary):
    assert {"rupee sign", "Rs.", "INR", "rupees after", "Indian grouping", "Hindi suffix", "Devanagari digits", "lakh", "invented link"} <= set(summary["fabricated_caught_by_format"])


def test_a_correct_derived_figure_is_blocked_by_design(summary):
    # grounding.py's module docstring: it compares values and does no arithmetic, so a correct computed figure is blocked and the
    # model is told (in the system prompt) to use the compute tool instead. If this ever stops being true, the docstring is stale.
    derived = summary["derived_but_correct_blocked"]
    assert derived["k"] == derived["n"]
